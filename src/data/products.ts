export function translateProductName(name: string, locale: string): string {
  if (locale === 'tr') return name;
  const translations = NAME_TRANSLATIONS[locale];
  if (!translations) return name;

  let translated = name;
  // Sort keys by length (longest first) to avoid partial replacements
  const sortedKeys = Object.keys(translations).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    translated = translated.replace(new RegExp(key, 'g'), translations[key]);
  }
  return translated;
}
